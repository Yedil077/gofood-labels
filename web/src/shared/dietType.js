/**
 * Тип питания блюда: «ПП» (правильное питание) или «Классический».
 *
 * Значение показывается на этикетке рядом со слоганом и определяется так:
 *   1. если у блюда явно проставлено `diet_type` ('pp' | 'classic') — берём его
 *      (это ручной выбор менеджера на экране печати / в карточке блюда);
 *   2. иначе — автоопределение по категории / названию блюда.
 *
 * Автоопределение — только по явным словам-маркерам, не по калорийности
 * (калорийность не является надёжным признаком и «придумывать» её нельзя).
 */

export const DIET_TYPES = { pp: 'ПП', classic: 'Классический' };

/* Маркеры «правильного питания» в категории/названии.
   `\b` в JS не работает на кириллице, поэтому границу слова задаём явно
   через «не буква и не цифра» (NB) с учётом кириллицы. */
const NB = '[^а-яёa-z0-9]';
const PP_RX = new RegExp(
  [
    `(^|${NB})пп(${NB}|$)`, // отдельное «ПП»
    'п\\s?/\\s?п', // «П/П»
    'пп[\\s\\-]?меню', // «ПП меню» / «ПП-меню»
    'правильн\\S*\\s+питани', // «правильное питание»
    'здоров\\S*\\s+питани', // «здоровое питание»
    `(^|${NB})диет`, // диета / диетическое
    `(^|${NB})фитнес`, // фитнес-меню
    `(^|${NB})лайт(${NB}|$)`,
    `(^|${NB})light(${NB}|$)`,
    'низкокалор',
  ].join('|'),
  'i'
);

/** Автоопределение по данным блюда (без учёта ручного `diet_type`). */
export function detectDietType(dish = {}) {
  const hay = [dish.category, dish.group, dish.name].filter(Boolean).join(' ');
  return PP_RX.test(hay) ? 'pp' : 'classic';
}

/** Итоговый тип: ручной выбор, иначе автоопределение. */
export function resolveDietType(dish = {}) {
  const v = dish.diet_type;
  return v === 'pp' || v === 'classic' ? v : detectDietType(dish);
}

/** Подпись для этикетки: «ПП» / «Классический». */
export function dietTypeLabel(dish = {}) {
  return DIET_TYPES[resolveDietType(dish)] || '';
}
